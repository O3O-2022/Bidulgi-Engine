// Game player (queue 7-4): what `bdg build` ships as <Game>.exe. No editor UI: it opens the project's start scene
// and runs it in play mode (built-in behaviours, C# Behaviours, camera shake) in a window set up from the project
// settings, drawing the scene through its first Camera like the editor's Game view.
//
// Content: <exe folder>/Content/game.bpak, unpacked once into %LOCALAPPDATA%/<company>/<name>/Content (only files
// that changed are written again; BDG_PLAYER_CACHE puts it elsewhere), then read from there. `--project <dir>` runs
// a project folder directly instead (developers; no packing). Scripts: <exe folder>/Managed + Scripts/*.dll.
// Log: Bidulgi.log next to the exe. `--frames N` quits after N frames (automated checks, hidden window).
