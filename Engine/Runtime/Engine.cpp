// Full-window view of the reference board with labels projected onto it.
std::unique_ptr<bdg::Widget> BuildRenderReferenceScreen(bdg_engine* e) {
  auto view = bdg::MakeCustom("render.view", [e](bdg::Widget& w, bdg::UIContext& ui) {
    bdg::Batch2D& b = ui.Batch();
    if (!e->board || !e->viewRT.Valid() || e->viewW <= 0 || e->viewH <= 0) return;
    b.Image(w.x, w.y, w.w, w.h, e->rhi.RenderTargetColor(e->viewRT), 0, 1, 1, 0); // render target rows are bottom-up
    const bdg::Color label{0.92f, 0.93f, 0.95f, 1}, shade{0.05f, 0.06f, 0.07f, 0.72f};
    for (const bdg::ReferenceBoard::Label& l : e->board->Labels()) {
      float px = 0, py = 0;
      if (!bdg::ProjectToPixel(e->board->camera, e->viewW, e->viewH, l.position, px, py)) continue;
      float x = w.x + px / e->viewW * w.w, y = w.y + (1.f - py / e->viewH) * w.h;
      float tw = ui.Measure(12, l.text);
      b.Rect(x - 5, y - 2, tw + 10, 19, shade, 4);
      ui.Text(x, y, 12, label, l.text);
    }
    std::string title = std::format("Render reference (queue 3-0, 3-1 glTF) · forward GGX, sun + sky hemisphere, sRGB output, "
                                    "no tone mapping · {} draws · {}x{} MSAA 4x", e->r3d->DrawsLastFrame(), e->viewW, e->viewH);
    b.Rect(w.x + 10, w.y + 10, ui.Measure(12, title) + 20, 24, shade, 6);
    ui.Text(w.x + 20, w.y + 14, 12, label, title);
  });
  view->width = bdg::Length::Fill();
  view->height = bdg::Length::Fill();
  return view;
}

// Renders the board at the view widget's size in drawable pixels (re-creating the target when it changes).
void RenderReferenceView(bdg_engine* e, const bdg::Widget& v, float scale) {
  int32_t pw = std::max(1, (int32_t)std::lround(v.w * scale)), ph = std::max(1, (int32_t)std::lround(v.h * scale));
  if (!e->viewRT.Valid() || pw != e->viewW || ph != e->viewH) {
    e->rhi.DestroyRenderTarget(e->viewRT);
    e->viewRT = e->rhi.CreateRenderTarget(pw, ph, 1); // the renderer does MSAA inside
    e->viewW = pw;
    e->viewH = ph;
  }
  if ((!e->board->probes.empty() || !e->board->volumes.empty() || e->board->lightmaps) && !e->boardGIDone) {
    // GI Tier 0: the board's probes, volume and lightmaps come from .cache/gi when the inputs match (D); otherwise
    // they are baked (two bounces) and saved. BDG_GI_READONLY=1 acts like a runtime build: load, never bake.
    e->boardGIDone = true;
    auto b0 = std::chrono::steady_clock::now();
    e->r3d->SetProbes(e->board->probes);
    e->r3d->SetVolume(e->board->volumes.empty() ? nullptr : &e->board->volumes[0]);
    const uint64_t hash = e->r3d->GIInputHash(e->board->Items(), e->board->light);
    const char* scr = std::getenv("BDG_SCREEN");
    const std::string path = (std::filesystem::current_path() / ".cache" / "gi" /
                              std::format("{}-{:016x}.bdggi", scr ? scr : "board", hash)).string();
    const char* cacheEnv = std::getenv("BDG_GI_CACHE");
    const bool useCache = !(cacheEnv && std::string(cacheEnv) == "0"), readOnly = std::getenv("BDG_GI_READONLY") != nullptr;
    std::string err;
    if (useCache && e->r3d->LoadGI(path, e->board->Items(), hash, &err)) {
      e->r3d->giCacheNote = "loaded " + path;
      bdg::LogInfo("gi: loaded {} in {:.0f} ms ({} probe(s), {} volume probe(s), {} lightmapped)", path,
                   std::chrono::duration<double, std::milli>(std::chrono::steady_clock::now() - b0).count(), e->r3d->BakedProbes(),
                   e->r3d->VolumeProbes(), e->r3d->LightmappedObjects());
    } else if (readOnly) {
      bdg::LogWarn("gi: no baked GI at {} ({}); read-only like a runtime build, so nothing is baked", path, err);
    } else {
      if (e->board->lightmaps) e->r3d->BakeLightmaps(e->board->Items(), e->board->light); // before the probes see the room
      e->r3d->BakeProbes(e->board->Items(), e->board->light);
      e->r3d->BakeProbes(e->board->Items(), e->board->light);
      bdg::LogInfo("gi: baked {} probe(s) and {} volume probe(s), 2 bounces, in {:.0f} ms", e->board->probes.size(), e->r3d->VolumeProbes(),
                   std::chrono::duration<double, std::milli>(std::chrono::steady_clock::now() - b0).count());
      if (useCache) {
        if (e->r3d->SaveGI(path, hash, &err)) {
          e->r3d->giCacheNote = "saved " + path;
          bdg::LogInfo("gi: saved {} ({} KB)", path, std::filesystem::file_size(path) / 1024);
        } else {
          bdg::LogWarn("gi: could not save the bake: {}", err);
        }
      }
    }
    if (std::getenv("BDG_GI_DIAGNOSE")) { // `bdg gi diagnose` until the CLI exists (2-7)
      std::string text = e->r3d->DiagnoseGI(e->board->Items());
      for (size_t a = 0, b; a < text.size(); a = b + 1) {
        b = text.find('\n', a);
        if (b == std::string::npos) b = text.size();
        bdg::LogInfo("gi diagnose: {}", text.substr(a, b - a));
      }
    }
  }
  auto t0 = std::chrono::steady_clock::now();
  bdg::RenderExtras boardExtras; // BDG_RENDER_VIEW=0..7: debug view of the board screens (7 = indirect light only)
  if (const char* rv = std::getenv("BDG_RENDER_VIEW")) boardExtras.view = (bdg::DebugView)std::clamp(std::atoi(rv), 0, 10);
  bdg::QualitySettings boardQ = e->boardQuality; // BDG_QUALITY_SET also applies to the board screens (experiments)
  if (const char* set = std::getenv("BDG_QUALITY_SET")) bdg::ApplyQualityOverrides(set, boardQ, nullptr);
  e->r3d->Render(e->viewRT, pw, ph, e->board->camera, e->board->light, e->board->Items(), e->board->clear, &boardExtras, &boardQ);
  e->boardRenderMs = std::chrono::duration<double, std::milli>(std::chrono::steady_clock::now() - t0).count();
}
