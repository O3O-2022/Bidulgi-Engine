  using T = bdg::InputEvent::Type;
  bdg::Widget* dw = e->editor->Find("dock");
  if (!dw || !dw->dock) return;
  bdg::DockState& d = *dw->dock;
  auto ev = [&](T type, float x, float y) { e->window.InjectEvent({type, x * scale, y * scale, type == T::MouseMove ? 0 : 1}); };
