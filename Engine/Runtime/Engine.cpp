// `bdg render compare` until the CLI exists (queue 3-9): BDG_RENDER_COMPARE=<baseline folder> visits camera bookmarks
// 1-9 of the open scene, compares each picture with <folder>/bookmark_<n>.png (FLIP-style error, Core/ImageCompare)
// and writes <out>/<n>.png plus <out>/<n>_diff.png (heat map); a missing baseline is created from this run.
// <out> = BDG_COMPARE_OUT or .cache/compare. Threshold: BDG_COMPARE_THRESHOLD (mean error, default 0.03).
void RenderCompareStep(bdg_engine* e, int frame, const char* baseDir) {
  namespace fs = std::filesystem;
  static int created = 0, failed = 0, compared = 0;
  static double worst = 0;
  const int slot = (frame - 4) / 4 + 1, phase = (frame - 4) % 4;
  if (frame < 4 || slot > 9) return;
  bdg::SceneView* sv = e->sceneView.get();
  if (phase == 0) { // move to the bookmark; the picture is read three frames later (shadow map and timers settle)
    if (!sv->JumpToBookmark(*e->model, slot)) bdg::LogInfo("compare: bookmark {} -", slot);
    return;
  }
  if (phase != 3 || sv->BookmarkName(*e->model, slot).empty()) return;
  int32_t w, h;
  std::vector<uint8_t> px;
  sv->ReadPixels(w, h, px);
  std::vector<uint8_t> top((size_t)w * h * 4); // render target rows are bottom-up
  for (int y = 0; y < h; ++y) std::memcpy(&top[(size_t)y * w * 4], &px[(size_t)(h - 1 - y) * w * 4], (size_t)w * 4);
  const char* outEnv = std::getenv("BDG_COMPARE_OUT");
  fs::path out = outEnv ? fs::path(outEnv) : fs::current_path() / ".cache" / "compare", base = fs::path(baseDir);
  std::error_code ec;
  fs::create_directories(out, ec);
  fs::create_directories(base, ec);
  double threshold = 0.03;
  if (const char* t = std::getenv("BDG_COMPARE_THRESHOLD")) threshold = std::atof(t);
  bdg::WritePNG((out / std::format("{}.png", slot)).string().c_str(), w, h, top.data(), false);
  fs::path basePng = base / std::format("bookmark_{}.png", slot);
  std::string name = sv->BookmarkName(*e->model, slot), result;
  int32_t bw = 0, bh = 0;
  std::vector<uint8_t> baseline;
  if (!fs::exists(basePng)) {
    bdg::WritePNG(basePng.string().c_str(), w, h, top.data(), false);
    ++created;
    result = "created";
    bdg::LogInfo("compare: bookmark {} {:<24} baseline created ({}x{})", slot, name, w, h);
  } else if (!bdg::LoadImageRGBA(basePng, bw, bh, baseline) || bw != w || bh != h) {
    ++failed;
    bdg::LogInfo("compare: bookmark {} {:<24} FAIL size {}x{} vs baseline {}x{}", slot, name, w, h, bw, bh);
  } else {
    bdg::ImageDiff d;
    bdg::CompareImages(baseline.data(), top.data(), w, h, d);
    bdg::WritePNG((out / std::format("{}_diff.png", slot)).string().c_str(), w, h, d.heat.data(), false);
    bool ok = d.mean <= threshold;
    failed += ok ? 0 : 1;
    ++compared;
    worst = std::max(worst, d.mean);
    bdg::LogInfo("compare: bookmark {} {:<24} flip={:.4f} max={:.3f} over0.1={:.2f}% base={:.2f} {}", slot, name, d.mean, d.max,
                 d.over * 100, threshold, ok ? "ok" : "FAIL");
  }
  if (slot == 9 || sv->BookmarkName(*e->model, slot + 1).empty())
    bdg::LogInfo("compare summary: compared={} created={} failed={} worst={:.4f} out={}", compared, created, failed, worst,
                 out.string());
}

// Scripted render reference check (BDG_REFSCENE_TEST=1 with the Tests/RenderReference project, queue 3-8):
// bookmarks 1 / 2 / 8 by key, the Albedo / Normal / Depth / Shadow views (Alt + digit), the wireframe chip,
// Ctrl + 5 storing a bookmark (one undo step), GPU pass timings.
void InjectRefSceneTest(bdg_engine* e, int frame, float scale) {
  using T = bdg::InputEvent::Type;
  bdg::SceneView* sv = e->sceneView.get();
  bdg::EditorModel* m = e->model.get();
  if (!sv || !m) return;
  auto* v = e->refSceneTestValues;
  bdg::Widget* sw = e->editor->Find("scene");
  if (!sw) return;
  float cx = sw->x + sw->w * 0.5f, cy = sw->y + sw->h * 0.5f;
  auto key = [&](bdg::Key k, bool ctrl = false, bool alt = false) {
    e->window.InjectEvent({T::MouseMove, cx * scale, cy * scale});
    bdg::InputEvent i{T::KeyDown};
    i.key = k;
    i.ctrl = ctrl;
    i.alt = alt;
    e->window.InjectEvent(i);
  };
  struct Shot { int32_t w = 0, h = 0; std::vector<uint8_t> px; };
  auto grab = [&] { Shot s; sv->ReadPixels(s.w, s.h, s.px); return s; };
  auto at = [&](const Shot& s, glm::vec3 p, int c[3]) {
    float x, y;
    c[0] = c[1] = c[2] = -1;
    if (!bdg::ProjectToPixel(sv->camera.ToCamera(), s.w, s.h, p, x, y) || x < 0 || y < 0 || x >= s.w || y >= s.h) return false;
    const uint8_t* q = &s.px[((size_t)y * s.w + (size_t)x) * 4];
    c[0] = q[0]; c[1] = q[1]; c[2] = q[2];
    return true;
  };
  // Zone 1: the matrix sphere r3 m0 (white dielectric) faces the camera at (0, 0.6, -1) + its radius toward +Z.
  const glm::vec3 sphereFront{0, 0.6f, -1 + 0.32f}, nearGold{0, 0.35f, 1}, farWall{0, 5.4f, -1};
  // Zone 2: the floating sphere's sun shadow on the ground, and open ground beside it.
  static const glm::vec3 toL = -glm::normalize(glm::vec3(0.321f, -0.766f, -0.557f)); // Sun rotation (-50, -30, 0)
  const glm::vec3 ball{31.8f, 1.4f, 0.5f};
  const glm::vec3 shade = ball - toL * (ball.y / toL.y), open{shade.x, 0, 1.6f};
  if (frame == 2) {
    v[0] = std::format("{}", m->scene.ObjectCount());
    key(bdg::Key::Num1);
  }
  if (frame == 4) {
    v[1] = std::format("{}", sv->camera.pivot.y == 2.4f && sv->camera.yaw == 0.f && sv->camera.distance == 10.5f ? 1 : 0);
    key(bdg::Key::Num2, false, true); // Alt + 2: albedo
  }
  if (frame == 6) {
    int c[3];
    at(grab(), sphereFront, c); // linear 0.85 white -> sRGB 237
    v[2] = sv->debugView == bdg::DebugView::Albedo && std::abs(c[0] - 237) <= 3 && std::abs(c[2] - 237) <= 3 ? "1" : std::format("0({},{},{})", c[0], c[1], c[2]);
    key(bdg::Key::Num3, false, true); // normal
  }
  if (frame == 8) {
    int c[3];
    at(grab(), sphereFront, c); // facing +Z: (0.5, 0.5, 1) -> (128, 128, 255)
    v[3] = c[2] > 235 && std::abs(c[0] - 128) < 30 && std::abs(c[1] - 128) < 30 ? "1" : std::format("0({},{},{})", c[0], c[1], c[2]);
    key(bdg::Key::Num6, false, true); // depth
  }
  if (frame == 10) {
    Shot s = grab();
    int n[3], f[3];
    at(s, nearGold, n);
    at(s, farWall, f);
    v[4] = n[0] >= 0 && f[0] > n[0] + 5 ? "1" : std::format("0({}<{})", n[0], f[0]); // farther = brighter
    key(bdg::Key::Num2);                      // bookmark 2: lights and shadows
    key(bdg::Key::Num7, false, true);         // shadow view
  }
  if (frame == 12) {
    Shot s = grab();
    int in[3], out[3];
    at(s, shade, in);
    at(s, open, out);
    v[5] = in[0] >= 0 && in[0] < 90 && out[0] > 200 ? "1" : std::format("0({},{})", in[0], out[0]);
    key(bdg::Key::Num1, false, true); // back to lit
  }
  static long long wireBefore = 0;
  auto cyan = [](const Shot& s) {
    long long n = 0;
    for (size_t i = 0; i + 3 < s.px.size(); i += 4) n += s.px[i] < 140 && s.px[i + 1] > 170 && s.px[i + 2] > 190;
    return n;
  };
  if (frame == 14) {
    wireBefore = cyan(grab());
    float x, y;
    if (sv->ChipCenter("wire", x, y)) {
      e->window.InjectEvent({T::MouseMove, x * scale, y * scale});
      e->window.InjectEvent({T::MouseDown, x * scale, y * scale, 1});
      e->window.InjectEvent({T::MouseUp, x * scale, y * scale, 1});
    }
  }
  static size_t undo0;
  if (frame == 16) {
    long long after = cyan(grab());
    v[6] = sv->wireframe && after > wireBefore + 500 ? "1" : std::format("0({}->{})", wireBefore, after);
    sv->camera.yaw = 42.f; // a new view, stored on key 5
    undo0 = m->bus.UndoDepth();
    key(bdg::Key::Num5, true);
  }
  if (frame == 18) {
    sv->camera.yaw = 0.f;
    bool stored = sv->JumpToBookmark(*m, 5) && sv->camera.yaw == 42.f && m->bus.UndoDepth() == undo0 + 1;
    v[7] = std::format("{}", stored ? 1 : 0);
    bdg::InputEvent z{T::KeyDown};
    z.key = bdg::Key::Z;
    z.ctrl = true;
    e->window.InjectEvent(z);
  }
  if (frame == 20) {
    sv->camera.yaw = 7.f;
    sv->JumpToBookmark(*m, 5);
    v[8] = std::format("{}", sv->camera.yaw == 0.f ? 1 : 0); // back to the generated "5 Post" view
    key(bdg::Key::Num8); // the materials zone at the potato tier
  }
  if (frame == 22) {
    v[9] = bdg::TierKey(sv->quality.tier);
    const auto& passes = e->r3d->Stats().passes;
    bool timed = false;
    for (const auto& p : passes) timed = timed || (std::string(p.name) == "scene" && p.ms > 0);
    v[10] = std::format("{}", timed ? 1 : 0);
  }
}

// Scripted quality tier check (BDG_QUALITY_TEST=1, queue 3-5): the same scene at potato / low / medium / high.
// Lighting: the Crystal's top and front faces differ only when lit. Shadows: ground in the Crystal's sun shadow
// is darker only from medium up. FXAA lowers the sum of squared neighbour differences (edges get softer); bloom brightens the ground beside a
// glowing Crystal; the top-bar badge steps to the next tier.
void InjectQualityTest(bdg_engine* e, int frame, float scale) {
  bdg::SceneView* sv = e->sceneView.get();
  bdg::EditorModel* m = e->model.get();
  if (!sv || !m) return;
  auto* v = e->qualityTestValues;
  struct Frame { int32_t w = 0, h = 0; std::vector<uint8_t> px; };
  auto grab = [&] { Frame f; sv->ReadPixels(f.w, f.h, f.px); return f; };
  auto lum = [&](const Frame& f, glm::vec3 p) {
    float x, y;
    if (!bdg::ProjectToPixel(sv->camera.ToCamera(), f.w, f.h, p, x, y) || x < 0 || y < 0 || x >= f.w || y >= f.h) return -1;
    const uint8_t* q = &f.px[((size_t)y * f.w + (size_t)x) * 4];
    return q[0] + q[1] + q[2];
  };
  auto variation = [](const Frame& f) {
    long long tv = 0;
    for (int y = 0; y < f.h; ++y)
      for (int x = 1; x < f.w; ++x)
        for (int c = 0; c < 3; ++c) { // squared steps: softening an edge (one jump into two halves) lowers it
          long long d = f.px[((size_t)y * f.w + x) * 4 + c] - f.px[((size_t)y * f.w + x - 1) * 4 + c];
          tv += d * d;
        }
    return tv;
  };
  // Crystal: 1 m placeholder box at (3, 0.5, 2). Its sun shadow falls toward +x / -z.
  const glm::vec3 top{3, 1.0f, 2}, front{3, 0.5f, 2.5f}, shade{3.7f, 0, 1.0f}, open{4.6f, 0, 1.0f}, beside{3.6f, 0.15f, 2.6f};
  auto describe = [&](const Frame& f) {
    int t = lum(f, top), fr = lum(f, front), s = lum(f, shade), o = lum(f, open);
    bool lit = std::abs(t - fr) > 10, shadow = s >= 0 && o > 0 && s * 10 < o * 8;
    return std::string(lit ? "lit" : "flat") + (shadow ? ",shadow" : ",noshadow");
  };
  const bdg::QualityTier tiers[4] = {bdg::QualityTier::Potato, bdg::QualityTier::Low, bdg::QualityTier::Medium, bdg::QualityTier::High};
  static long long tvFxaa = 0;
  static int besideMedium = 0;
  if (frame >= 2 && frame <= 14 && (frame - 2) % 4 == 0) sv->quality = bdg::QualityPreset(tiers[(frame - 2) / 4]);
  if (frame >= 4 && frame <= 16 && (frame - 4) % 4 == 0) {
    int i = (frame - 4) / 4;
    Frame f = grab();
    v[i] = describe(f) + (i == 3 ? std::format(",msaa{}", e->r3d->LastQuality().msaa) : "");
    if (i == 2) tvFxaa = variation(f);
  }
  if (frame == 17) { // medium once more, without FXAA
    sv->quality = bdg::QualityPreset(bdg::QualityTier::Medium);
    sv->quality.fxaa = false;
  }
  if (frame == 19) {
    v[4] = std::format("{}", tvFxaa > 0 && tvFxaa < variation(grab()) ? 1 : 0);
    bdg::Command c; // a glowing Crystal: bloom shows around it from high up
    c.name = "set";
    c.target = "g8";
    c.args = R"({"path":"MeshRenderer.material","value":"M_Glow"})";
    std::string err;
    m->bus.Execute(c, &err);
    sv->quality = bdg::QualityPreset(bdg::QualityTier::Medium);
  }
  if (frame == 21) {
    besideMedium = lum(grab(), beside);
    sv->quality = bdg::QualityPreset(bdg::QualityTier::High);
  }
  if (frame == 23) {
    int b = lum(grab(), beside);
    v[5] = b > besideMedium + 6 ? "1" : std::format("0({}->{})", besideMedium, b);
    if (bdg::Widget* badge = e->editor->Find("tool.quality")) { // click: high -> ultra
      using T = bdg::InputEvent::Type;
      float x = (badge->x + badge->w * 0.5f) * scale, y = (badge->y + badge->h * 0.5f) * scale;
      e->window.InjectEvent({T::MouseMove, x, y});
      e->window.InjectEvent({T::MouseDown, x, y, 1});
      e->window.InjectEvent({T::MouseUp, x, y, 1});
    }
  }
  if (frame == 25) {
    bdg::Widget* badge = e->editor->Find("tool.quality");
    v[6] = std::format("{}", badge && badge->text == "초고사양" && sv->quality.tier == bdg::QualityTier::Ultra ? 1 : 0);
  }
}

// Scripted material check (BDG_MATERIAL_TEST=1 with BDG_ASSETS = an empty folder, queue 3-1b): writes a small project
// (two materials, an instance, two textures), assigns them through commands and reads the rendered colours back.
void InjectMaterialTest(bdg_engine* e, int frame) {
  namespace fs = std::filesystem;
  bdg::SceneView* sv = e->sceneView.get();
  bdg::EditorModel* m = e->model.get();
  if (!sv || !m || !e->assetsOpen) return;
  auto* v = e->materialTestValues;
  fs::path root = fs::path(std::u8string((const char8_t*)e->assets.Root().c_str()));
  auto write = [&](const char* rel, const std::string& text) {
    fs::create_directories((root / rel).parent_path());
    std::FILE* f = _wfopen((root / rel).c_str(), L"wb");
    if (f) { std::fwrite(text.data(), 1, text.size(), f); std::fclose(f); }
  };
  // 64x64 picture in 4 quadrants (top-left first) and a gently bumpy normal map.
  static const uint8_t quad[4][3] = {{230, 60, 160}, {60, 200, 220}, {250, 150, 30}, {120, 90, 230}};
  auto set = [&](const char* id, const char* material) {
    bdg::Command c;
    c.name = "set";
    c.target = id;
    c.args = std::format(R"({{"path":"MeshRenderer.material","value":"{}"}})", material);
    std::string err;
    if (!m->bus.Execute(c, &err)) bdg::LogError("material test: {}", err);
  };
  auto pixel = [&](glm::vec3 world, int rgb[3]) {
    int32_t w, h;
    std::vector<uint8_t> px;
    sv->ReadPixels(w, h, px);
    float x, y;
    rgb[0] = rgb[1] = rgb[2] = -1;
    if (!bdg::ProjectToPixel(sv->camera.ToCamera(), w, h, world, x, y) || x < 0 || y < 0 || x >= w || y >= h) return;
    const uint8_t* p = &px[((size_t)y * w + (size_t)x) * 4];
    rgb[0] = p[0]; rgb[1] = p[1]; rgb[2] = p[2];
  };
  auto close = [](const int a[3], int r, int g, int b, int tol) {
    return std::abs(a[0] - r) <= tol && std::abs(a[1] - g) <= tol && std::abs(a[2] - b) <= tol;
  };
  static size_t undo0;
  if (frame == 2) {
    std::vector<uint8_t> img(64 * 64 * 4), nrm(64 * 64 * 4);
    for (int y = 0; y < 64; ++y)
      for (int x = 0; x < 64; ++x) {
        const uint8_t* c = quad[(y / 32) * 2 + x / 32];
        uint8_t* p = &img[(y * 64 + x) * 4];
        p[0] = c[0]; p[1] = c[1]; p[2] = c[2]; p[3] = 255;
        float nx = 0.3f * std::sin(x * 0.4f), ny = 0.3f * std::cos(y * 0.4f), nz = std::sqrt(1 - nx * nx - ny * ny);
        uint8_t* q = &nrm[(y * 64 + x) * 4];
        q[0] = (uint8_t)std::lround((nx * 0.5f + 0.5f) * 255); q[1] = (uint8_t)std::lround((ny * 0.5f + 0.5f) * 255);
        q[2] = (uint8_t)std::lround((nz * 0.5f + 0.5f) * 255); q[3] = 255;
      }
    std::vector<uint8_t> png;
    bdg::EncodePNG(64, 64, img.data(), false, png);
    write("Textures/T_Check_D.png", std::string(png.begin(), png.end()));
    bdg::EncodePNG(64, 64, nrm.data(), false, png);
    write("Textures/T_Bumps_N.png", std::string(png.begin(), png.end()));
    write("Materials/M_TestRed.material", "{\"material\":\"M_TestRed\",\"shading\":\"unlit\",\"blend\":\"opaque\"}\n"
                                           "{\"param\":\"BaseColor\",\"type\":\"color\",\"value\":\"#d02020\"}\n");
    write("Materials/MI_TestBlue.matinst", "{\"instance\":\"MI_TestBlue\",\"parent\":\"M_TestRed\"}\n"
                                            "{\"set\":\"BaseColor\",\"value\":\"#2050e0\"}\n");
    write("Materials/M_Textured.material", "{\"material\":\"M_Textured\",\"shading\":\"unlit\"}\n"
                                            "{\"param\":\"BaseColorMap\",\"type\":\"texture\",\"value\":\"Textures/T_Check_D.png\"}\n"
                                            "{\"param\":\"NormalMap\",\"type\":\"texture\",\"value\":\"Textures/T_Bumps_N.png\"}\n");
    e->assets.Refresh();
    e->materials.Invalidate();
    undo0 = m->bus.UndoDepth();
    set("g8", "M_TestRed");
    set("g6", "MI_TestBlue");
    set("g5", "Materials/M_Textured.material");
  }
  if (frame == 4) {
    int c[3];
    glm::vec3 center;
    float r;
    sv->ObjectCenter(*m, "g8", center, r);
    pixel(center, c);
    auto shown = [&](int r, int g, int b, int out[3]) { // what the tier's tone map makes of an unlit sRGB colour
      bdg::Color lin = bdg::SrgbToLinear((uint8_t)r, (uint8_t)g, (uint8_t)b);
      const bdg::QualitySettings& q = sv->quality;
      float ch[3] = {lin.r, lin.g, lin.b};
      for (int k = 0; k < 3; ++k) {
        float x = ch[k] * q.exposure;
        x = q.toneMap ? bdg::ToneMapACES(x) : std::clamp(x, 0.f, 1.f);
        out[k] = (int)std::lround((x <= 0.0031308f ? x * 12.92f : 1.055f * std::pow(x, 1.f / 2.4f) - 0.055f) * 255.f);
      }
    };
    int red[3], blue[3], q0[3], q3[3];
    shown(208, 32, 32, red);
    shown(32, 80, 224, blue);
    shown(quad[0][0], quad[0][1], quad[0][2], q0);
    shown(quad[3][0], quad[3][1], quad[3][2], q3);
    v[0] = std::format("{}", close(c, red[0], red[1], red[2], 3) ? 1 : 0);
    sv->ObjectCenter(*m, "g6", center, r);
    pixel(center + glm::vec3(0, -0.25f, 0), c); // below the Weapon child
    v[1] = std::format("{}", close(c, blue[0], blue[1], blue[2], 3) ? 1 : 0);
    int tl[3], br[3]; // ground plane: picture top-left at (-x, -z), bottom-right at (+x, +z)
    pixel({-4.5f, 0, -4.5f}, tl); // cell centres: the 1 m grid lines are drawn over the ground
    pixel({1.5f, 0, 3.5f}, br);
    bool texOk = close(tl, q0[0], q0[1], q0[2], 8) && close(br, q3[0], q3[1], q3[2], 8);
    v[2] = texOk ? "1" : std::format("0(tl={},{},{} br={},{},{})", tl[0], tl[1], tl[2], br[0], br[1], br[2]);
    auto preset = [&](const char* rel) {
      std::vector<uint8_t> b;
      bdg::ReadFileBytes(root / (std::string(rel) + ".meta"), b);
      return std::string(bdg::PresetName(bdg::ParseTextureSettings(std::string(b.begin(), b.end()), rel).preset));
    };
    v[3] = preset("Textures/T_Check_D.png") + "," + preset("Textures/T_Bumps_N.png");
    v[4] = std::format("{}", e->materials.Cooker().GetStats().cooked);
    e->materials.Shutdown(); // drop the GPU copies: the next lookups read the cooked DDS files
    e->materials.Invalidate();
  }
  if (frame == 6) {
    v[5] = std::format("{}", e->materials.Cooker().GetStats().loaded);
    std::string formats;
    for (const char* rel : {"Textures/T_Check_D.png", "Textures/T_Bumps_N.png"}) {
      const bdg::AssetRecord* r = e->assets.ByPath(rel);
      bdg::CookedTexture t;
      for (auto& f : fs::directory_iterator(root.parent_path() / ".cache" / "cooked"))
        if (r && f.path().filename().string().starts_with(r->guid)) bdg::ReadDDS(f.path(), t);
      formats += std::string(formats.empty() ? "" : ",") + (t.format == bdg::CookedFormat::BC7_SRGB ? "BC7_SRGB" : t.format == bdg::CookedFormat::BC5 ? "BC5" : "?");
      formats += std::format("x{}", t.mips.size());
    }
    v[6] = formats;
    v[7] = std::format("{}", m->bus.UndoDepth() - undo0);
  }
}

// Scripted gizmo check (BDG_GIZMO_TEST=1, queue 3-3) on the Crystal (g8, at 3, 0.5, 2): real mouse drags on the
// handles through the scene view, each drag one undo step, Esc cancels, W/E/R switch tools, Ctrl snaps, X local axes.
// Scripted check of 3-3b (BDG_SNAP_TEST=1): three cubes added by command; grid snap from the Snap chip, vertex
// snap (V), surface snap (Ctrl+Shift), align and distribute from the chips, the ruler of the Measure tool.
// Scripted check of 3-6 (BDG_PLAY_TEST=1): a Rotator added in the edited world turns the Crystal while playing;
// edits made while playing (a move, a value) can be undone among themselves; Stop restores the edited world and
// its history; the banner keeps the two changed values as one undo step; the Game view renders from the camera.
void TogglePlay(bdg_engine* e);
void InjectPlayTest(bdg_engine* e, int frame) {
  using T = bdg::InputEvent::Type;
  bdg::EditorModel* m = e->model.get();
  if (!m || !e->sceneView) return;
  auto* v = e->playTestValues;
  auto run = [&](const char* name, const char* target, const char* args) {
    bdg::Command c;
    c.name = name;
    c.target = target;
    c.args = args;
    std::string err;
    if (!m->bus.Execute(c, &err)) bdg::LogError("play test: {} {}: {}", name, target, err);
  };
  auto transform = [&](const char* id) -> bdg::Transform* {
    bdg::SceneObject* o = m->scene.Find(id);
    bdg::Component* c = o ? o->Find("Transform") : nullptr;
    return c ? static_cast<bdg::Transform*>(c->data) : nullptr;
  };
  auto health = [&]() -> int {
    bdg::SceneObject* o = m->scene.Find("g6");
    bdg::Component* c = o ? o->Find("Health") : nullptr;
    return c ? static_cast<const bdg::Health*>(c->data)->current : -1;
  };
  auto click = [&](const char* id) {
    bdg::Widget* w = e->editor->Find(id);
    if (!w || w->hidden) { bdg::LogError("play test: {} is not clickable", id); return; }
    const float s = e->editor->Scale();
    e->window.InjectEvent({T::MouseMove, (w->x + w->w * 0.5f) * s, (w->y + w->h * 0.5f) * s});
    e->window.InjectEvent({T::MouseDown, (w->x + w->w * 0.5f) * s, (w->y + w->h * 0.5f) * s, 1});
    e->window.InjectEvent({T::MouseUp, (w->x + w->w * 0.5f) * s, (w->y + w->h * 0.5f) * s, 1});
  };
  static bdg::Vec3 rot0, pos0;
  static size_t depth0;
  static uint64_t game0;
  if (frame == 2) {
    run("addcomp", "g8", R"({"type":"Rotator","value":{"speed":[0,90,0]}})");
    rot0 = transform("g8")->rotation;
    pos0 = transform("g8")->position;
    depth0 = m->bus.UndoDepth();
    game0 = e->sceneView->GameFrames();
    TogglePlay(e);
    v[0] = std::format("{}", e->play.Playing() && m->playing && m->bus.UndoDepth() == 0 ? 1 : 0);
  }
  static uint64_t frames0;
  static double time0;
  if (frame == 4) { // 3-6b: pause holds the game
    v[1] = std::format("{}", transform("g8")->rotation.y != rot0.y ? 1 : 0); // it ran before the pause
    SetPlayPaused(e, true);
    frames0 = e->play.Frames();
    time0 = e->play.Time();
  }
  if (frame == 6) {
    // the frame drawn while paused has the paused (warn) border; the game did not move
    int32_t w = 0, h = 0;
    e->window.GetDrawableSize(w, h);
    std::vector<uint8_t> px;
    e->rhi.ReadPixels(w, h, px);
    const uint8_t* p = &px[((size_t)(h / 2) * w + 3) * 4];
    const bdg::Color warn = e->theme.C("warn");
    const bool border = std::abs(p[0] - warn.r * 255) < 40 && std::abs(p[1] - warn.g * 255) < 40 && std::abs(p[2] - warn.b * 255) < 40;
    v[8] = std::format("{}", e->play.Frames() == frames0 && e->play.Paused() ? 1 : 0);
    v[11] = std::format("{}", border ? 1 : 0);
    StepPlay(e);
  }
  if (frame == 7) { // exactly one frame of 1/60 s, then still paused
    v[9] = std::format("{}", e->play.Frames() == frames0 + 1 && std::abs(e->play.Time() - time0 - bdg::PlayMode::kStepSeconds) < 1e-9 &&
                                     e->play.Paused() ? 1 : 0);
    SetPlayPaused(e, false);
    if (bdg::Widget* f = e->editor->Find("tool.timescale"); f && f->onCommit) {
      f->text2 = "9"; // clamped to 4x
      f->onCommit(*f);
      v[10] = std::format("{}", e->play.TimeScale() == 4.f && f->text2 == "4" ? 1 : 0);
      f->text2 = "1";
      f->onCommit(*f);
    }
  }
  if (frame == 8) {
    run("set", "g8", R"({"path":"Transform.position","value":[3,2,2]})");
    run("set", "g6", R"({"path":"Health.current","value":10})");
    run("set", "g6", R"({"path":"Health.maxHealth","value":500})");
    std::string err;
    m->bus.Undo(&err); // maxHealth back to 100: undo works inside play mode
  }
  if (frame == 9) { // the Inspector marks what was changed while playing (the undone maxHealth is not)
    bdg::Widget* cur = e->editor->Find("f.Health.current");
    bdg::Widget* max = e->editor->Find("f.Health.maxHealth");
    v[12] = std::format("{}", cur && cur->marked && max && !max->marked ? 1 : 0);
  }
  if (frame == 10) {
    v[2] = std::format("{}", health() == 10 && m->bus.UndoDepth() == 2 ? 1 : 0);
    TogglePlay(e);
  }
  if (frame == 12) {
    const bdg::Transform* t = transform("g8");
    bdg::Widget* banner = e->editor->Find("play.keep.banner");
    v[3] = std::format("{}", t && t->rotation.y == rot0.y && t->position.y == pos0.y && health() == 100 && m->bus.UndoDepth() == depth0 &&
                                     !m->playing ? 1 : 0);
    v[4] = std::format("{}", banner && !banner->hidden ? e->play.Pending().size() : 0);
    v[7] = std::format("{}", e->sceneView->GameFrames() > game0 + 3 ? 1 : 0);
    click("play.keep");
  }
  if (frame == 14) {
    const bdg::Transform* t = transform("g8");
    bdg::Widget* banner = e->editor->Find("play.keep.banner");
    v[5] = std::format("{}", t && t->position.y == 2 && health() == 10 && m->bus.UndoDepth() == depth0 + 1 && banner && banner->hidden ? 1 : 0);
    std::string err;
    m->bus.Undo(&err); // the kept values are one step
  }
  if (frame == 16) {
    const bdg::Transform* t = transform("g8");
    v[6] = std::format("{}", t && t->position.y == pos0.y && health() == 100 ? 1 : 0);
  }
}

