    const bdg::DockRect& r = d.nodes[d.FindLeaf("hierarchy")].rect;
    e->dockTestW0 = r.w;
    float sx = r.x + r.w + bdg::DockState::kGap * 0.5f, sy = r.y + r.h * 0.5f;
