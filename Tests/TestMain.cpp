// Unit tests: BidulgiTests [filter]   (runs every TEST_CASE whose name contains the filter)
#include "bdg_test.h"
#include "Core/Command.h"
#include <cstring>
#include <format>

void bdg_reflect_register_BidulgiTests();  // generated by bdg_reflect() (CMakeLists.txt)
void bdg_reflect_register_BidulgiEngine(); // engine components (Transform, Light, ...)

void BuildDeterminismScene(bdg::Scene& s); // Tests/DeterminismTests.cpp

// Second-process half of the determinism test: BidulgiTests --replay-dump <log.jsonl> <out.txt>
static int ReplayDump(const char* log, const char* out) {
  bdg::Scene s;
  BuildDeterminismScene(s);
  bdg::CommandBus bus(s);
  std::string err;
  if (!bus.Replay(log, &err)) { std::printf("replay failed: %s\n", err.c_str()); return 1; }
  std::string text = s.Dump() + std::format("undo_depth={}\n", bus.UndoDepth());
  std::FILE* f = std::fopen(out, "wb");
  if (!f) return 1;
  std::fwrite(text.data(), 1, text.size(), f);
  std::fclose(f);
  return 0;
}

int main(int argc, char** argv) {
  bdg_reflect_register_BidulgiEngine();
  bdg_reflect_register_BidulgiTests();
  if (argc == 4 && std::strcmp(argv[1], "--replay-dump") == 0) return ReplayDump(argv[2], argv[3]);
  const char* filter = argc > 1 ? argv[1] : nullptr;
  int ran = 0;
  for (const auto& c : bdgtest::Cases()) {
    if (filter && !std::strstr(c.name, filter)) continue;
    int before = bdgtest::Failures();
    c.fn();
    ++ran;
    std::printf("[%s] %s\n", bdgtest::Failures() == before ? " ok " : "FAIL", c.name);
  }
  std::printf("tests: %d cases, %d checks, %d failures\n", ran, bdgtest::Checks(), bdgtest::Failures());
  return bdgtest::Failures() ? 1 : 0;
}
